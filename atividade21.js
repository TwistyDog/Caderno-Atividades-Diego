let linguagens = ["Javascript", "Python", "Java"];

// 1 Adicione C+ ao final
linguagens.push("C+");
console.log(linguagens);

// 2 Adicione Typescript ao inicio
linguagens.unshift("TypeScript");
console.log(linguagens);

// 3 Remova o ultimo elemento
linguagens.pop();
console.log(linguagens);

// 4 apresentar a quantidade de elementos
console.log(linguagens.length);

// 5 apresentar o conteudo completo do array.
console.log(linguagens);